import fs from "node:fs";
import path from "node:path";
import { getProjectRoot } from "./db.js";

export function loadProjectReadmes(slugs: string[]): Record<string, string> {
  const root = getProjectRoot();
  const readmeDir = path.join(root, "content", "projects");
  const readmes: Record<string, string> = {};

  for (const slug of slugs) {
    const filePath = path.join(readmeDir, `${slug}.md`);
    if (fs.existsSync(filePath)) {
      readmes[slug] = fs.readFileSync(filePath, "utf-8");
    }
  }

  return readmes;
}

export function generateProjectReadmesFile(readmes: Record<string, string>): string {
  const body = JSON.stringify(readmes, null, 2);
  return `// AUTO-GENERATED by scripts/build-content.ts — do not edit by hand.
// Source: content/projects/*.md
// Regenerate: npm run sync:github-projects && npm run build:content

export const projectReadmes: Record<string, string> = ${body};
`;
}

export function writeProjectReadmesFile(slugs: string[]): void {
  const readmes = loadProjectReadmes(slugs);
  const outputPath = path.join(getProjectRoot(), "src", "content", "project-readmes.ts");
  fs.writeFileSync(outputPath, generateProjectReadmesFile(readmes), "utf-8");
}
