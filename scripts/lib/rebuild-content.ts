const NAV_ITEMS = [
  { id: "resumes", label: "Resumes" },
  { id: "experience", label: "Experience" },
  { id: "projects", label: "Projects" },
  { id: "skills", label: "Skills" },
  { id: "contact", label: "Contact" },
] as const;

function serializeValue(value: unknown, indent: number): string {
  const spaces = "  ".repeat(indent);

  if (value === null) {
    return "null";
  }

  if (typeof value === "string") {
    return JSON.stringify(value);
  }

  if (typeof value === "boolean" || typeof value === "number") {
    return String(value);
  }

  if (Array.isArray(value)) {
    if (value.length === 0) {
      return "[]";
    }

    const items = value.map((item) => `${spaces}  ${serializeValue(item, indent + 1)}`);
    return `[\n${items.join(",\n")},\n${spaces}]`;
  }

  if (typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>);
    if (entries.length === 0) {
      return "{}";
    }

    const lines = entries.map(([key, val]) => {
      return `${spaces}  ${key}: ${serializeValue(val, indent + 1)}`;
    });

    return `{\n${lines.join(",\n")},\n${spaces}}`;
  }

  return JSON.stringify(value);
}

const SHOWCASE_IMAGE_EXTENSIONS = new Set([".png", ".jpg", ".jpeg", ".webp", ".gif", ".avif"]);

/**
 * Attach the published screenshot files of each project
 * (public/assets/projects/<slug>/*) so sections like the showcase
 * carousel can reference every available image, not only the cover.
 */
function attachProjectScreenshots(content: SiteContent): SiteContent {
  const assetsDir = path.join(getProjectRoot(), "public", "assets", "projects");

  return {
    ...content,
    projects: content.projects.map((project) => {
      let screenshots: string[] = [];
      try {
        screenshots = fs
          .readdirSync(path.join(assetsDir, project.slug), { withFileTypes: true })
          .filter(
            (entry) =>
              entry.isFile() &&
              SHOWCASE_IMAGE_EXTENSIONS.has(path.extname(entry.name).toLowerCase()),
          )
          .map((entry) => `/assets/projects/${project.slug}/${entry.name}`)
          .sort();
      } catch {
        screenshots = [];
      }

      if (screenshots.length === 0) {
        return project;
      }

      return { ...project, screenshots };
    }),
  };
}

function generateSiteFile(content: SiteContent): string {
  const body = serializeValue(content, 1);

  return `// AUTO-GENERATED by scripts/build-content.ts — do not edit by hand.
// Source: data/portfolio.db
// Regenerate: npm run build:content

import type { SiteContent } from "./types";

export const siteContent: SiteContent = ${body};

export const navItems = ${serializeValue(NAV_ITEMS, 0)} as const;
`;
}

function generateRecruitmentFile(content: ReturnType<typeof buildRecruitmentContent>): string {
  const body = serializeValue(content, 1);

  return `// AUTO-GENERATED by scripts/build-content.ts — do not edit by hand.
// Source: data/portfolio.db
// Regenerate: npm run build:content

import type { RecruitmentContent } from "./types";

export const recruitmentContent: RecruitmentContent = ${body};
`;
}

export type RebuildContentResult = {
  sitePath: string;
  recruitmentPath: string;
  projectReadmesPath: string;
};

export function rebuildProjectReadmesFromDb(): string {
  migrateLegacyReadmeFiles();
  const db = openDatabaseReadonly();
  try {
    const slugs = fetchProjects(db).map((project) => project.slug);
    writeProjectReadmesFile(slugs);
    return path.join(getProjectRoot(), "src", "content", "project-readmes.ts");
  } finally {
    db.close();
  }
}

export function rebuildContent(): RebuildContentResult {
  const db = openDatabaseReadonly();

  try {
    const profile = fetchSiteProfile(db);
    if (!profile) {
      throw new Error("site_profile está vazio. Execute: npm run db:reset");
    }

    const rawContent = mapSiteContent({
      profile,
      professionalProfiles: fetchProfessionalProfiles(db),
      professionalProfileChips: fetchProfessionalProfileChips(db),
      experience: fetchExperience(db),
      projects: fetchProjects(db),
      education: fetchEducation(db),
      certifications: fetchCertifications(db),
      skills: fetchSkills(db),
      articles: fetchArticles(db),
    });

    const content = validateSiteContent(attachProjectScreenshots(rawContent));
    const outputPath = path.join(getProjectRoot(), "src", "content", "site.ts");
    fs.writeFileSync(outputPath, generateSiteFile(content), "utf-8");
    writeProjectReadmesFile(content.projects.map((project) => project.slug));

    const recruitment = buildRecruitmentContent(
      content,
      fetchProfessionalProfiles(db),
      fetchProfileCvRows(db),
      fetchProfileCvSkillRows(db),
    );
    const recruitmentPath = path.join(getProjectRoot(), "src", "content", "recruitment.ts");
    fs.writeFileSync(recruitmentPath, generateRecruitmentFile(recruitment), "utf-8");

    const projectReadmesPath = path.join(getProjectRoot(), "src", "content", "project-readmes.ts");

    return { sitePath: outputPath, recruitmentPath, projectReadmesPath };
  } finally {
    db.close();
  }
}
