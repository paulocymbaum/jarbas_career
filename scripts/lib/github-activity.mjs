/**
 * GitHub contribution calendar fetch + snapshot serialization.
 */

const CONTRIBUTION_QUERY = `
query ContributionCalendar($from: DateTime!, $to: DateTime!) {
  viewer {
    login
    contributionsCollection(from: $from, to: $to) {
      contributionCalendar {
        totalContributions
        weeks {
          contributionDays {
            date
            contributionCount
          }
        }
      }
    }
  }
}
`;

function pad(value) {
  return String(value).padStart(2, "0");
}

export function formatUtcDate(date) {
  return `${date.getUTCFullYear()}-${pad(date.getUTCMonth() + 1)}-${pad(date.getUTCDate())}`;
}

export function contributionRange(daysBack = 364) {
  const to = new Date();
  to.setUTCHours(23, 59, 59, 999);

  const from = new Date(to);
  from.setUTCDate(from.getUTCDate() - daysBack);
  from.setUTCHours(0, 0, 0, 0);

  return {
    from: `${formatUtcDate(from)}T00:00:00Z`,
    to: `${formatUtcDate(to)}T23:59:59Z`,
    fromDate: formatUtcDate(from),
    toDate: formatUtcDate(to),
  };
}

export async function fetchContributionCalendar(token) {
  const range = contributionRange();
  const response = await fetch("https://api.github.com/graphql", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
      "User-Agent": "portfolio-cv-sync",
    },
    body: JSON.stringify({
      query: CONTRIBUTION_QUERY,
      variables: {
        from: range.from,
        to: range.to,
      },
    }),
  });

  if (!response.ok) {
    throw new Error(`GitHub GraphQL HTTP ${response.status}: ${await response.text()}`);
  }

  const payload = await response.json();
  if (payload.errors?.length) {
    throw new Error(payload.errors.map((error) => error.message).join("; "));
  }

  const viewer = payload.data?.viewer;
  const calendar = viewer?.contributionsCollection?.contributionCalendar;
  if (!viewer || !calendar) {
    throw new Error("GitHub GraphQL response missing contribution calendar data.");
  }

  const weeks = calendar.weeks.map((week) =>
    week.contributionDays.map((day) => ({
      date: day.date,
      count: day.contributionCount,
    })),
  );

  return {
    username: viewer.login,
    totalContributions: calendar.totalContributions,
    includesPrivateContributions: true,
    fetchedAt: new Date().toISOString(),
    from: range.fromDate,
    to: range.toDate,
    weeks,
  };
}

export function generateGithubActivityModule(snapshot) {
  const body = JSON.stringify(snapshot, null, 2);
  return `// AUTO-GENERATED by scripts/sync-github-activity.mjs — do not edit by hand.
// Source: data/github-activity.json
// Regenerate: npm run sync:github-activity

import type { GithubActivitySnapshot } from "./types";

export const githubActivity: GithubActivitySnapshot = ${body};
`;
}

export function emptyGithubActivitySnapshot(username = "your-username") {
  return {
    username,
    totalContributions: 0,
    includesPrivateContributions: false,
    fetchedAt: null,
    from: null,
    to: null,
    weeks: [],
  };
}
